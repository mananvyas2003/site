import { createHash, randomBytes, scryptSync, timingSafeEqual } from "node:crypto";

/**
 * There are exactly two users. Ever. Their identity is config, not a table you
 * sign up into — the row in `users` is created on first sign-in from these
 * constants.
 *
 * Auth is a password each, not a shared one. The PRD is right that a single
 * shared password kills the whole app: `both sides` depends on knowing *who*
 * wrote which version, and who uploaded which photo. Two passwords keep that
 * and drop the Google dependency.
 */
export type Handle = "manno" | "momo";

export const PEOPLE: Record<Handle, {
  handle: Handle;
  displayName: string;
  accent: string;
  emailKey: string;
  passwordKey: string;
  hashKey: string;
}> = {
  manno: {
    handle: "manno",
    displayName: "Manan",
    accent: "#2E5E4E",
    emailKey: "MANNO_EMAIL",
    passwordKey: "MANNO_PASSWORD",
    hashKey: "MANNO_PASSWORD_HASH",
  },
  momo: {
    handle: "momo",
    displayName: "Nehal",
    accent: "#9B3B66",
    emailKey: "MOMO_EMAIL",
    passwordKey: "MOMO_PASSWORD",
    hashKey: "MOMO_PASSWORD_HASH",
  },
};

export const HANDLES = Object.keys(PEOPLE) as Handle[];
export const OTHER: Record<Handle, Handle> = { manno: "momo", momo: "manno" };

export function isHandle(v: unknown): v is Handle {
  return v === "manno" || v === "momo";
}

/** Email from env, or a local placeholder before setup. */
export function emailFor(handle: Handle): string {
  const set = process.env[PEOPLE[handle].emailKey]?.trim().toLowerCase();
  return set || `${handle}@mannomomo.local`;
}

/** Resolve a login email back to manno or momo. */
export function handleFromEmail(raw: string): Handle | null {
  const email = raw.trim().toLowerCase();
  if (!email) return null;
  for (const handle of HANDLES) {
    if (emailFor(handle) === email) return handle;
  }
  return null;
}

